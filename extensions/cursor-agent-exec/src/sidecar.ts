/**
 * The CLIProxyAPI sidecar behind the Subscriptions provider.
 *
 * Started on demand (the Settings page or the first turn routed to it) with a
 * generated config under the provider's data directory, bound to 127.0.0.1
 * and gated by the provider's API key. It runs with CLIProxyAPI's local
 * password, which turns on a keep-alive watchdog: the sidecar exits once
 * nobody has pinged it for 10 seconds, so it never outlives Cursor. A new
 * extension host (window reload, `bun run dev` reload) adopts a sidecar that
 * is still alive instead of racing it for the port.
 */
import { execFile, spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { closeSync, existsSync, openSync } from 'node:fs';
import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { connect } from 'node:net';
import path from 'node:path';
import type { SidecarConfig } from '../../../src/vs/workbench/contrib/localMode/common/subscriptions.js';

export interface Sidecar {
	config: SidecarConfig;
	/** Management key (CLIProxyAPI's local password), new for every start. */
	mgmtKey: string;
	pid: number;
	binary: string;
	version?: string;
	exited: boolean;
	timer: ReturnType<typeof setInterval>;
}

interface State {
	current: Sidecar | undefined;
	/** Serializes starts: two requests must not both spawn on one port. */
	queue: Promise<unknown>;
}

declare global {
	var __cursorLocalModeSidecar: State | undefined;
}

// On globalThis so a hot reload of this file (bun run dev) keeps the sidecar.
globalThis.__cursorLocalModeSidecar ??= { current: undefined, queue: Promise.resolve() };
const state = globalThis.__cursorLocalModeSidecar;

const KEEP_ALIVE_MS = 3000;
const START_TIMEOUT_MS = 20_000;

export const NOT_INSTALLED =
	'CLIProxyAPI is not installed. Run `bun run cliproxyapi` in the cursor-re checkout, `brew install cliproxyapi`, or set CURSOR_CLIPROXYAPI_BIN.';

/**
 * CURSOR_CLIPROXYAPI_BIN, then the copy `bun run cliproxyapi` puts in
 * app/resources/cliproxyapi, then PATH (plus Homebrew, which an app started
 * from the Dock does not have on its PATH).
 */
export function findBinary(env: NodeJS.ProcessEnv = process.env, dir = __dirname): string | undefined {
	const override = env.CURSOR_CLIPROXYAPI_BIN?.trim();
	if (override) {
		return override;
	}
	// dist/ of cursor-agent-exec -> app/resources/cliproxyapi
	const bundled = path.resolve(dir, '../../../resources/cliproxyapi/cli-proxy-api');
	if (existsSync(bundled)) {
		return bundled;
	}
	const dirs = [...(env.PATH ?? '').split(path.delimiter), '/opt/homebrew/bin', '/usr/local/bin'];
	for (const d of dirs.filter(Boolean)) {
		for (const name of ['cli-proxy-api', 'cliproxyapi']) {
			const file = path.join(d, name);
			if (existsSync(file)) {
				return file;
			}
		}
	}
	return undefined;
}

const yaml = (value: string) => JSON.stringify(value);

/** config.yaml for one start (CLIProxyAPI v8 layout). */
export function renderConfig(config: SidecarConfig, mgmtKey: string): string {
	return [
		'# Generated by Cursor RE (Settings > Models > Subscriptions) on every start; edits are lost.',
		'config-version: 8',
		'server:',
		'  host: "127.0.0.1"',
		`  port: ${config.port}`,
		'management:',
		'  allow-remote: false',
		// Also passed as -password, which alone does not survive CLIProxyAPI's
		// first config reload (management routes would turn off again).
		`  secret-key: ${yaml(mgmtKey)}`,
		'  disable-control-panel: true',
		'access:',
		'  api-keys:',
		`    - ${yaml(config.apiKey)}`,
		'routing:',
		`  strategy: ${yaml(config.strategy ?? 'round-robin')}`,
		// Keeps a conversation on one account, so its prompt cache keeps hitting.
		'  session-affinity: true',
		'requests:',
		`  proxy-url: ${yaml(config.proxyUrl ?? '')}`,
		'oauth:',
		`  auth-dir: ${yaml(path.join(config.dataDir, 'auths'))}`,
		'observability:',
		'  usage:',
		'    usage-statistics-enabled: false',
		'',
	].join('\n');
}

function restartKey(config: SidecarConfig): string {
	return JSON.stringify([config.port, config.apiKey, config.dataDir]);
}

function checkConfig(config: SidecarConfig): void {
	if (!Number.isInteger(config?.port) || config.port < 1024 || config.port > 65_535) {
		throw new Error('The Subscriptions port must be a number from 1024 to 65535.');
	}
	if (typeof config.apiKey !== 'string' || config.apiKey.trim() === '') {
		throw new Error('The Subscriptions provider has no local API key.');
	}
	if (typeof config.dataDir !== 'string' || !path.isAbsolute(config.dataDir)) {
		throw new Error('The Subscriptions data directory is not an absolute path.');
	}
}

function alive(pid: number): boolean {
	try {
		process.kill(pid, 0);
		return true;
	} catch {
		return false;
	}
}

async function waitFor(check: () => boolean | Promise<boolean>, timeoutMs: number): Promise<boolean> {
	const deadline = Date.now() + timeoutMs;
	while (Date.now() < deadline) {
		if (await check()) {
			return true;
		}
		await new Promise((r) => setTimeout(r, 150));
	}
	return false;
}

async function ping(port: number, mgmtKey: string): Promise<boolean> {
	try {
		const res = await fetch(`http://127.0.0.1:${port}/keep-alive`, {
			headers: { authorization: `Bearer ${mgmtKey}` },
			signal: AbortSignal.timeout(2000),
		});
		return res.ok;
	} catch {
		return false;
	}
}

/** CLIProxyAPI's version, which only management responses carry. */
async function version(port: number, mgmtKey: string): Promise<string | undefined> {
	try {
		const res = await fetch(`http://127.0.0.1:${port}/v8/management/config/server/port`, {
			headers: { authorization: `Bearer ${mgmtKey}` },
			signal: AbortSignal.timeout(2000),
		});
		return res.headers.get('x-cpa-version') || undefined;
	} catch {
		return undefined;
	}
}

function keepAlive(sidecar: Sidecar): ReturnType<typeof setInterval> {
	let misses = 0;
	const timer = setInterval(async () => {
		if (await ping(sidecar.config.port, sidecar.mgmtKey)) {
			misses = 0;
		} else if (++misses >= 3 || !alive(sidecar.pid)) {
			markExited(sidecar);
		}
	}, KEEP_ALIVE_MS);
	timer.unref?.();
	return timer;
}

function markExited(sidecar: Sidecar): void {
	sidecar.exited = true;
	clearInterval(sidecar.timer);
	if (state.current === sidecar) {
		state.current = undefined;
	}
}

interface Saved {
	pid: number;
	port: number;
	apiKey: string;
	mgmtKey: string;
	binary: string;
}

const savedPath = (config: SidecarConfig) => path.join(config.dataDir, 'sidecar.json');

async function readSaved(config: SidecarConfig): Promise<Saved | undefined> {
	try {
		const s = JSON.parse(await readFile(savedPath(config), 'utf8'));
		return typeof s?.pid === 'number' && typeof s?.mgmtKey === 'string' ? s : undefined;
	} catch {
		return undefined;
	}
}

/**
 * A sidecar a previous extension host started on this data directory: adopted
 * when it matches, stopped when it doesn't (it holds the auth directory).
 */
async function adopt(config: SidecarConfig): Promise<Sidecar | undefined> {
	const saved = await readSaved(config);
	if (saved === undefined || !alive(saved.pid) || !(await ping(saved.port, saved.mgmtKey))) {
		return undefined;
	}
	if (saved.port === config.port && saved.apiKey === config.apiKey) {
		const sidecar: Sidecar = {
			config: { ...config, strategy: undefined, proxyUrl: undefined },
			mgmtKey: saved.mgmtKey,
			pid: saved.pid,
			binary: saved.binary,
			version: await version(saved.port, saved.mgmtKey),
			exited: false,
			timer: undefined as never,
		};
		sidecar.timer = keepAlive(sidecar);
		return sidecar;
	}
	try {
		process.kill(saved.pid, 'SIGTERM');
	} catch {}
	await waitFor(() => !alive(saved.pid), 5000);
	return undefined;
}

async function tail(file: string, lines = 12): Promise<string> {
	try {
		return (await readFile(file, 'utf8')).trimEnd().split('\n').slice(-lines).join('\n');
	} catch {
		return '';
	}
}

function listening(port: number): Promise<boolean> {
	return new Promise((resolve) => {
		const socket = connect({ host: '127.0.0.1', port });
		const done = (busy: boolean) => {
			socket.destroy();
			resolve(busy);
		};
		socket.once('connect', () => done(true));
		socket.once('error', () => done(false));
		socket.setTimeout(1000, () => done(false));
	});
}

const portInUse = (port: number) => new Error(`Port ${port} is already in use. Pick another port under Advanced.`);

async function start(config: SidecarConfig): Promise<Sidecar> {
	const binary = findBinary();
	if (binary === undefined) {
		throw new Error(NOT_INSTALLED);
	}
	if (await listening(config.port)) {
		throw portInUse(config.port);
	}
	await mkdir(path.join(config.dataDir, 'auths'), { recursive: true, mode: 0o700 });
	await chmod(config.dataDir, 0o700);
	const mgmtKey = randomBytes(24).toString('hex');
	const configFile = path.join(config.dataDir, 'config.yaml');
	await writeFile(configFile, renderConfig(config, mgmtKey), { mode: 0o600 });
	await chmod(configFile, 0o600);

	// The log is the child's stdout itself (not a pipe), so the sidecar keeps
	// running, and can be adopted, if this extension host goes away first.
	const logFile = path.join(config.dataDir, 'sidecar.log');
	const log = openSync(logFile, 'w', 0o600);
	const env = { ...process.env };
	// CLIProxyAPI turns on remote management when this is set.
	delete env.MANAGEMENT_PASSWORD;
	let sidecar: Sidecar | undefined;
	let child: ReturnType<typeof spawn>;
	try {
		child = spawn(binary, ['-config', configFile, '-password', mgmtKey], {
			cwd: config.dataDir,
			stdio: ['ignore', log, log],
			env,
		});
	} finally {
		closeSync(log);
	}
	let exit: string | undefined;
	child.once('error', (e) => {
		exit = e.message;
	});
	child.once('exit', (code, signal) => {
		exit ??= signal ? `killed by ${signal}` : `exit code ${code}`;
		sidecar !== undefined && markExited(sidecar);
	});

	// Ready once our own key works: someone else answering on the port does not count.
	const up = await waitFor(async () => exit !== undefined || (await ping(config.port, mgmtKey)), START_TIMEOUT_MS);
	if (exit !== undefined || !up) {
		child.kill();
		const output = await tail(logFile);
		if (/address already in use/iu.test(output)) {
			throw portInUse(config.port);
		}
		throw new Error(
			`CLIProxyAPI (${binary}) did not start${exit ? ` (${exit})` : ''}.${output ? `\n\n${output}` : ''}`,
		);
	}
	sidecar = {
		config: { ...config },
		mgmtKey,
		pid: child.pid!,
		binary,
		version: await version(config.port, mgmtKey),
		exited: false,
		timer: undefined as never,
	};
	sidecar.timer = keepAlive(sidecar);
	const saved: Saved = { pid: sidecar.pid, port: config.port, apiKey: config.apiKey, mgmtKey, binary };
	await writeFile(savedPath(config), JSON.stringify(saved), { mode: 0o600 });
	return sidecar;
}

/** Applies settings that don't need a restart (strategy, default proxy). */
async function apply(sidecar: Sidecar, config: SidecarConfig): Promise<void> {
	const strategy = config.strategy ?? 'round-robin';
	const proxyUrl = config.proxyUrl ?? '';
	if (sidecar.config.strategy === strategy && (sidecar.config.proxyUrl ?? '') === proxyUrl) {
		return;
	}
	await management(sidecar, 'PATCH', '/config', { routing: { strategy }, requests: { 'proxy-url': proxyUrl } });
	sidecar.config = { ...sidecar.config, strategy, proxyUrl };
}

/** The running sidecar for `config`, started (or restarted) as needed. */
export function ensureSidecar(config: SidecarConfig): Promise<Sidecar> {
	const run = state.queue.then(async () => {
		checkConfig(config);
		let sidecar = state.current;
		if (sidecar !== undefined && (sidecar.exited || restartKey(sidecar.config) !== restartKey(config))) {
			await stopSidecar();
			sidecar = undefined;
		}
		if (sidecar === undefined) {
			sidecar = (await adopt(config)) ?? (await start(config));
			state.current = sidecar;
		}
		await apply(sidecar, config);
		return sidecar;
	});
	state.queue = run.catch(() => {});
	return run;
}

export async function stopSidecar(): Promise<void> {
	const sidecar = state.current;
	if (sidecar === undefined) {
		return;
	}
	markExited(sidecar);
	if (alive(sidecar.pid)) {
		try {
			process.kill(sidecar.pid, 'SIGTERM');
		} catch {}
		await waitFor(() => !alive(sidecar.pid), 5000);
	}
}

/** Calls CLIProxyAPI's management API (v8). */
export async function management(
	sidecar: Sidecar,
	method: string,
	pathAndQuery: string,
	body?: unknown,
	timeoutMs = 15_000,
): Promise<any> {
	const url = `http://127.0.0.1:${sidecar.config.port}/v8/management${pathAndQuery}`;
	let res: Response;
	try {
		res = await fetch(url, {
			method,
			headers: {
				authorization: `Bearer ${sidecar.mgmtKey}`,
				...(body === undefined ? {} : { 'content-type': 'application/json' }),
			},
			body: body === undefined ? undefined : JSON.stringify(body),
			signal: AbortSignal.timeout(timeoutMs),
		});
	} catch (e) {
		throw new Error(`CLIProxyAPI did not answer ${method} ${pathAndQuery}: ${(e as Error).message}`);
	}
	const text = await res.text();
	let json: any;
	try {
		json = text === '' ? {} : JSON.parse(text);
	} catch {
		json = undefined;
	}
	if (!res.ok) {
		throw new Error(String(json?.error ?? json?.message ?? `HTTP ${res.status} from CLIProxyAPI`));
	}
	return json ?? {};
}

/** Opens a sign-in page in the user's browser. */
export function openExternal(url: string): void {
	if (process.platform === 'darwin' && /^https?:\/\//iu.test(url)) {
		execFile('/usr/bin/open', [url], () => {});
	}
}
